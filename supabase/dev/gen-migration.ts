/* Genera supabase/migrations/20261020000000_majobella.sql (y una migración aparte por cada tabla añadida después,
   las que tienen «migration» en el esquema) a partir de functions/_shared/core/schema.ts
   Uso: npm run migration */
import { writeFileSync } from 'node:fs';
import { TABLES, type ColType } from '../functions/_shared/core/schema.ts';

const SQL_TYPE: Record<ColType, string> = { text: 'text', int: 'integer', num: 'numeric', bool: 'boolean', date: 'date', time: 'time', ts: 'timestamptz', json: 'jsonb' };
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const out: string[] = [
  '-- MAJOBELLA · Base de datos (PostgreSQL en Supabase)',
  '-- Generado por supabase/dev/gen-migration.ts a partir de functions/_shared/core/schema.ts. No editar a mano.',
  '--',
  '-- Seguridad: todas las tablas tienen RLS activado y ninguna política para "anon" ni "authenticated".',
  '-- Solo el backend (Edge Function "api", con la llave de servicio) lee y escribe. La web y las apps',
  '-- nunca tocan las tablas directamente: piden todo a la API, que valida cada acción.',
  '',
  'set check_function_bodies = off;',
  '',
];

function tableSql(t: (typeof TABLES)[number]): string[] {
  const out: string[] = [];
  const lines: string[] = [];
  lines.push(t.pk ? '  row_id bigint generated by default as identity unique' : '  row_id bigint generated by default as identity primary key');
  for (const c of t.cols) {
    let l = `  ${c.col} ${SQL_TYPE[c.type]}`;
    if (c.key === t.pk) l += ' primary key';
    else if (c.notNull) l += ' not null';
    if (c.default) l += ` default ${c.default}`;
    if (c.check) l += ` check (${c.col} ${c.check})`;
    lines.push(l);
  }
  lines.push('  creado_en timestamptz not null default now()');
  lines.push('  actualizado_en timestamptz not null default now()');
  out.push(`create table if not exists public.${t.table} (\n${lines.join(',\n')}\n);`);
  out.push(`comment on table public.${t.table} is ${q(t.comment)};`);
  for (const ix of t.indexes || []) out.push(`create index if not exists ${t.table}_${ix}_idx on public.${t.table} (${ix});`);
  out.push(`alter table public.${t.table} enable row level security;`);
  out.push(`revoke all on public.${t.table} from anon, authenticated;`);
  out.push(`drop trigger if exists ${t.table}_actualizado on public.${t.table};`);
  out.push(`create trigger ${t.table}_actualizado before update on public.${t.table} for each row execute function public.majobella_actualizado();`);
  out.push('');
  return out;
}
for (const t of TABLES.filter((x) => !x.migration)) out.push(...tableSql(t));

const header = `create or replace function public.majobella_actualizado() returns trigger language plpgsql set search_path = pg_catalog as $
begin new.actualizado_en = now(); return new; end $$;
`;

const extra = `
-- Códigos únicos (tarjetas, paquetes vendidos y códigos de descuento)
create unique index if not exists tarjetas_codigo_unico on public.tarjetas (upper(codigo)) where codigo is not null and codigo <> '';
create unique index if not exists bonos_codigo_unico on public.bonos (upper(codigo)) where codigo is not null and codigo <> '';
create unique index if not exists promociones_codigo_unico on public.promociones (upper(codigo)) where codigo is not null and codigo <> '';

-- Correos y avisos: los más recientes primero
create index if not exists correos_fecha_idx on public.correos (fecha desc);
create index if not exists errores_fecha_idx on public.errores (fecha desc);
create index if not exists cache_vence_idx on public.cache (vence);

-- Archivos (Storage): carpeta privada para fichas, consentimientos y comprobantes; pública para la web
insert into storage.buckets (id, name, public, file_size_limit)
values ('fichas', 'fichas', false, 15728640), ('publico', 'publico', true, 15728640)
on conflict (id) do nothing;
`;

writeFileSync(new URL('../migrations/20261020000000_majobella.sql', import.meta.url), [out[0], out[1], out[2], out[3], out[4], out[5], out[6], header, ...out.slice(7), extra].join('\n'));
const later = [...new Set(TABLES.map((t) => t.migration).filter(Boolean))] as string[];
for (const m of later) {
  const ts = TABLES.filter((t) => t.migration === m);
  writeFileSync(new URL(`../migrations/${m}.sql`, import.meta.url), [
    `-- MAJOBELLA · ${ts.map((t) => t.name).join(', ')}`,
    '-- Generado por supabase/dev/gen-migration.ts a partir de functions/_shared/core/schema.ts. No editar a mano.',
    '',
    ...ts.flatMap(tableSql),
  ].join('\n'));
}
console.log('Migraciones generadas:', TABLES.length, 'tablas', later.length ? `(+ ${later.join(', ')})` : '');
