-- MAJOBELLA · Plantillas de consentimiento y registro previo al pago.
create table if not exists public.plantillas_consentimiento (
  row_id bigint generated by default as identity unique,
  id text primary key,
  nombre text not null,
  descripcion text,
  texto text not null default '',
  estado text not null default 'borrador' check (estado in ('activo','borrador','archivado')),
  preguntas jsonb not null default '[]'::jsonb,
  actualizado timestamptz not null default now()
);
alter table public.plantillas_consentimiento enable row level security;
revoke all on public.plantillas_consentimiento from anon, authenticated;
comment on table public.plantillas_consentimiento is 'Consentimientos editados por el estudio; acceso exclusivo desde API autenticada.';

alter table public.servicios add column if not exists consent_template_id text;
alter table public.reservas add column if not exists consentimientos_json jsonb;
create index if not exists servicios_consent_template_idx on public.servicios(consent_template_id);
