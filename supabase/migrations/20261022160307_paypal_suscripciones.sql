-- MAJOBELLA · Integración de suscripciones PayPal.
-- El backend guarda únicamente IDs, importes y estados; NUNCA datos de tarjeta.
alter table public.planes_membresia
  add column if not exists paypal_product_id text,
  add column if not exists paypal_plan_id text,
  add column if not exists paypal_precio_usd numeric,
  add column if not exists paypal_plan_version text;
alter table public.membresias
  add column if not exists paypal_subscription_id text,
  add column if not exists paypal_estado text,
  add column if not exists paypal_pago_id text,
  add column if not exists paypal_pagos_fallidos integer default 0,
  add column if not exists paypal_precio_usd numeric;
create unique index if not exists membresias_paypal_subscription_unique
  on public.membresias(paypal_subscription_id) where paypal_subscription_id is not null;
create table if not exists public.pagos_membresia (
  row_id bigint generated by default as identity unique,
  id text primary key,
  membresia_id text not null references public.membresias(id),
  paypal_subscription_id text not null,
  correo text not null,
  nombre_plan text,
  monto_usd numeric not null,
  monto_rd numeric not null,
  moneda text not null default 'USD',
  estado text not null default 'completado',
  creado timestamptz not null default now(),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists pagos_membresia_membresia_id_idx on public.pagos_membresia(membresia_id);
create index if not exists pagos_membresia_paypal_subscription_id_idx on public.pagos_membresia(paypal_subscription_id);
alter table public.pagos_membresia enable row level security;
revoke all on public.pagos_membresia from anon, authenticated;
comment on table public.pagos_membresia is 'Libro de cobros recurrentes verificados por PayPal, sin datos PCI.';
