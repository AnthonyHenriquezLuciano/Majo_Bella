-- MAJOBELLA · Categorías -> servicios -> subservicios.
-- Migración aditiva: conserva IDs, precios, citas y promociones existentes.
create table if not exists public.categorias (
  row_id bigint generated by default as identity unique,
  id text primary key,
  nombre text not null,
  orden integer not null default 0,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
comment on table public.categorias is 'Categorías del catálogo MAJOBELLA; administración exclusiva.';
alter table public.categorias enable row level security;
revoke all on public.categorias from anon, authenticated;
drop trigger if exists categorias_actualizado on public.categorias;
create trigger categorias_actualizado before update on public.categorias
for each row execute function public.majobella_actualizado();

insert into public.categorias (id, nombre, orden, activo) values
  ('cejas', 'Cejas', 1, true),
  ('pestanas', 'Pestañas', 2, true),
  ('faciales', 'Faciales', 3, true),
  ('micropigmentacion', 'Micropigmentación', 4, true),
  ('depilacion', 'Depilación', 5, true),
  ('otros', 'Otros', 6, true)
on conflict (id) do nothing;

alter table public.servicios
  add column if not exists categoria_id text,
  add column if not exists padre_id text,
  add column if not exists tipo text not null default 'servicio',
  add column if not exists orden integer not null default 0,
  add column if not exists descripcion text;
update public.servicios
set categoria_id = case
  when id in ('faciales','cejas','pestanas','micropigmentacion','depilacion') then id
  else 'otros'
end
where categoria_id is null or categoria_id = '';
update public.servicios set tipo = 'servicio' where tipo is null;
create index if not exists servicios_categoria_orden_idx on public.servicios (categoria_id, orden);
create index if not exists servicios_padre_idx on public.servicios (padre_id);
