-- MAJOBELLA · Membresías mensuales de renovación gestionada (sin cobros automáticos).
create table if not exists public.planes_membresia (
  row_id bigint generated by default as identity unique,
  id text primary key,
  nombre text not null,
  descripcion text,
  precio_rd numeric not null default 0 check (precio_rd >= 0),
  sesiones_mes integer not null default 1 check (sesiones_mes between 1 and 99),
  servicios jsonb not null default '[]'::jsonb,
  beneficios text,
  estado text not null default 'borrador' check (estado in ('borrador','activo','archivado')),
  orden integer not null default 0,
  actualizado timestamptz default now(),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create table if not exists public.membresias (
  row_id bigint generated by default as identity unique,
  id text primary key,
  plan_id text not null references public.planes_membresia(id),
  nombre_plan text,
  clienta text,
  correo text not null,
  telefono text,
  estado text not null default 'solicitada' check (estado in ('solicitada','activa','pausada','cancelada','vencida')),
  inicio date,
  vence date,
  sesiones_mes integer not null default 1 check (sesiones_mes between 1 and 99),
  sesiones_usadas integer not null default 0 check (sesiones_usadas >= 0),
  precio_rd numeric not null default 0 check (precio_rd >= 0),
  servicios jsonb not null default '[]'::jsonb,
  metodo_pago text,
  pagado_en timestamptz,
  notas text,
  creada timestamptz not null default now(),
  actualizada timestamptz default now(),
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists membresias_correo_idx on public.membresias(correo);
create index if not exists membresias_plan_id_idx on public.membresias(plan_id);
create index if not exists membresias_estado_idx on public.membresias(estado);
alter table public.planes_membresia enable row level security;
alter table public.membresias enable row level security;
revoke all on public.planes_membresia from anon, authenticated;
revoke all on public.membresias from anon, authenticated;
comment on table public.membresias is 'Inscripciones de clientas: nunca activar una membresía sin confirmar el pago fuera de la plataforma.';
