-- Libro de auditoría PayPal (eventos firmados y reembolsos).
create table if not exists public.eventos_paypal (
 row_id bigint generated by default as identity unique,
 id text primary key, tipo text, recurso text, referencia text,
 estado text, detalle text, recibido timestamptz,
 creado_en timestamptz default now(), actualizado_en timestamptz default now()
);
create index if not exists eventos_paypal_tipo_idx on public.eventos_paypal(tipo);
create index if not exists eventos_paypal_recibido_idx on public.eventos_paypal(recibido);
alter table public.eventos_paypal enable row level security;
revoke all on public.eventos_paypal from anon,authenticated;
create table if not exists public.reembolsos_paypal (
 row_id bigint generated by default as identity unique,
 id text primary key, referencia text, tipo text, paypal_pago_id text, paypal_reembolso_id text,
 monto_usd numeric, monto_rd numeric, estado text, motivo text, iniciado_por text,
 creado timestamptz, actualizado timestamptz,
 creado_en timestamptz default now(), actualizado_en timestamptz default now()
);
create index if not exists reembolsos_paypal_referencia_idx on public.reembolsos_paypal(referencia);
create index if not exists reembolsos_paypal_estado_idx on public.reembolsos_paypal(estado);
alter table public.reembolsos_paypal enable row level security;
revoke all on public.reembolsos_paypal from anon,authenticated;